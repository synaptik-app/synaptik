#!/usr/bin/env node
// Turns the test bench's fixtures (testbench/fixtures/*.md) into a module the
// UI tests can import: the test kit runs tests with no file access, and imports
// only code files. One source for the manual bench and the automated tests.
//
//   node scripts/fixtures.mjs           write hosts/claude-code/tests/fixtures.generated.ts
//   node scripts/fixtures.mjs --check   fail if that file is not what the fixtures give

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'testbench', 'fixtures')
const target = join(root, 'hosts', 'claude-code', 'tests', 'fixtures.generated.ts')

const SLEEP = /^<<sleep (\d+)>>$/

// A fixture's reply, split into the pieces a real run produces: a `<<sleep N>>`
// line is a tool call, so the text before and after it are separate messages.
// Its checks are the list under "What to check".
function parse(text) {
  const pieces = []
  let current = []
  for (const line of text.split('\n')) {
    if (SLEEP.test(line.trim())) {
      pieces.push(current.join('\n').trim())
      current = []
    } else {
      current.push(line)
    }
  }
  pieces.push(current.join('\n').trim())

  const checks = []
  let inChecks = false
  for (const line of text.split('\n')) {
    if (/^#{1,6}\s+What to check\s*$/.test(line)) inChecks = true
    else if (/^#{1,6}\s/.test(line)) inChecks = false
    else if (inChecks && line.startsWith('- ')) checks.push(line.slice(2).trim())
  }
  return { pieces: pieces.filter(Boolean), checks }
}

const names = readdirSync(source)
  .filter(f => f.endsWith('.md'))
  .sort()
const body = names
  .map(file => {
    const { pieces, checks } = parse(readFileSync(join(source, file), 'utf8'))
    return `  ${JSON.stringify(file.replace(/\.md$/, ''))}: {
    pieces: ${JSON.stringify(pieces, null, 2).replace(/\n/g, '\n    ')},
    checks: ${JSON.stringify(checks, null, 2).replace(/\n/g, '\n    ')},
  },`
  })
  .join('\n')

const out = `// GENERATED by scripts/fixtures.mjs from testbench/fixtures/*.md — do not edit.
// Run \`node scripts/fixtures.mjs\` after changing a fixture.

export type Fixture = { readonly pieces: readonly string[]; readonly checks: readonly string[] }

export const FIXTURES: Readonly<Record<string, Fixture>> = {
${body}
}
`

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== out) {
    console.error('tests/fixtures.generated.ts is out of date: run `node scripts/fixtures.mjs`')
    process.exit(1)
  }
  console.log('fixtures up to date')
} else {
  writeFileSync(target, out)
  console.log(`wrote ${names.length} fixtures to ${target.slice(root.length + 1)}`)
}
